#!/usr/bin/env python3
"""
Slate icon atlas generator.

Every glyph is hand-drawn below as 16x16 ASCII art:
    '#'  opaque white pixel
    '+'  50% alpha white pixel (anti-aliased corners, used sparingly)
    '.'  transparent

Design rules (DESIGN.md "Visual language"): Lucide/Phosphor-style shapes translated to the pixel
grid, 2 px main strokes with 1 px detail, ~2 px padding (content in columns/rows 2..13; round
shapes and gears may touch 1..14), optically centred, white on transparent - they are tinted at
draw time. Slate draws icons with nearest-neighbour sampling at 16, 12, 10 and 8 px: at 8 px only
the odd rows/columns of the source survive, so anything that must stay visible is 2 px thick.

Outputs:
  common/core/src/main/resources/assets/slate/textures/gui/icons.png   16 columns of 16x16 cells
  common/core/src/main/java/dev/fallingcloud/slate/core/gfx/Icon.java   enum constants, atlas order
  tools/icons-preview.png                                               4x sheet with names

The list order IS the atlas order and the enum order: append new glyphs at the END, never reorder
or rename existing ones (code refers to them by name, saved layouts may refer to them by ordinal).

Usage:  python tools/icons.py            regenerate everything
        python tools/icons.py --check    validate the glyph list only (no files written)
        python tools/icons.py --review DIR   also write per-glyph review sheets (16/12/10/8 px) to DIR
"""
from __future__ import annotations

import math
import os
import sys

from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
ATLAS_PATH = os.path.join(ROOT, "common", "core", "src", "main", "resources", "assets", "slate",
                          "textures", "gui", "icons.png")
JAVA_PATH = os.path.join(ROOT, "common", "core", "src", "main", "java", "dev", "fallingcloud", "slate",
                         "core", "gfx", "Icon.java")
PREVIEW_PATH = os.path.join(HERE, "icons-preview.png")

CELL = 16
COLUMNS = 16

# Palette used only by the preview sheet (matches the dark skin defaults in DESIGN.md).
PREVIEW_BG = (0x16, 0x16, 0x15, 255)
PREVIEW_CELL = (0x22, 0x22, 0x21, 255)
PREVIEW_BORDER = (0x33, 0x33, 0x2F, 255)
PREVIEW_TEXT = (0xEC, 0xEA, 0xE4, 255)
PREVIEW_MUTED = (0xA1, 0x9F, 0x97, 255)
PREVIEW_ACCENT = (0xD9, 0x80, 0x5E, 255)

# (name, rows) in atlas order.
GLYPHS: list[tuple[str, list[str]]] = []


def icon(name: str, art: str) -> None:
    """Register one glyph. Validates the grid so a typo never silently shifts the atlas."""
    rows = [line for line in art.strip("\n").splitlines()]
    if len(rows) != CELL:
        raise SystemExit(f"{name}: expected {CELL} rows, got {len(rows)}")
    for i, row in enumerate(rows):
        if len(row) != CELL:
            raise SystemExit(f"{name}: row {i} has {len(row)} chars, expected {CELL}: {row!r}")
        bad = set(row) - set(".#+")
        if bad:
            raise SystemExit(f"{name}: row {i} has invalid chars {sorted(bad)}")
    if any(existing == name for existing, _ in GLYPHS):
        raise SystemExit(f"{name}: duplicate glyph name")
    if not name.isidentifier() or name != name.upper():
        raise SystemExit(f"{name}: must be an UPPER_CASE Java identifier")
    GLYPHS.append((name, rows))


def glyph_image(rows: list[str]) -> Image.Image:
    im = Image.new("RGBA", (CELL, CELL), (0, 0, 0, 0))
    px = im.load()
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch == "#":
                px[x, y] = (255, 255, 255, 255)
            elif ch == "+":
                px[x, y] = (255, 255, 255, 128)
    return im


def atlas_rows() -> int:
    return (len(GLYPHS) + COLUMNS - 1) // COLUMNS


def render_atlas() -> Image.Image:
    sheet = Image.new("RGBA", (COLUMNS * CELL, atlas_rows() * CELL), (0, 0, 0, 0))
    for i, (_, rows) in enumerate(GLYPHS):
        sheet.paste(glyph_image(rows), ((i % COLUMNS) * CELL, (i // COLUMNS) * CELL))
    return sheet


JAVA_HEAD = """package dev.fallingcloud.slate.core.gfx;

/**
 * Every glyph in {@code assets/slate/textures/gui/icons.png}. GENERATED by {@code tools/icons.py} -
 * edit the glyph list there and regenerate; the atlas is 16 columns of 16x16 cells in ordinal order.
 */
public enum Icon {
"""

JAVA_TAIL = """
    public static final int CELL = 16;
    public static final int COLUMNS = 16;

    public int u() { return (ordinal() % COLUMNS) * CELL; }

    public int v() { return (ordinal() / COLUMNS) * CELL; }

    /** Atlas height in cells, for the texture size passed to blit. */
    public static int rows() { return (values().length + COLUMNS - 1) / COLUMNS; }
}
"""


def java_source() -> str:
    names = [name for name, _ in GLYPHS]
    lines = []
    for i in range(0, len(names), 8):
        chunk = ", ".join(names[i:i + 8])
        last = i + 8 >= len(names)
        lines.append("    " + chunk + (";" if last else ","))
    return JAVA_HEAD + "\n".join(lines) + "\n" + JAVA_TAIL


def _font(size: int):
    try:
        return ImageFont.load_default(size=size)
    except TypeError:  # Pillow < 10.1
        return ImageFont.load_default()


def render_preview(scale: int = 4) -> Image.Image:
    """The whole sheet, scaled, on the dark skin background, one labelled cell per glyph."""
    cell_w, cell_h = 96, 100
    pad = 12
    title_h = 36
    cols = COLUMNS
    rows = atlas_rows()
    im = Image.new("RGBA", (pad * 2 + cols * cell_w, title_h + pad * 2 + rows * cell_h), PREVIEW_BG)
    d = ImageDraw.Draw(im)
    big = _font(16)
    small = _font(11)
    tiny = _font(9)
    d.text((pad, 10), f"Slate icon atlas - {len(GLYPHS)} glyphs, {cols} x {rows} cells of {CELL} px, "
                      f"shown at {scale}x", font=big, fill=PREVIEW_TEXT)
    for i, (name, grid) in enumerate(GLYPHS):
        cx = pad + (i % cols) * cell_w
        cy = title_h + pad + (i // cols) * cell_h
        d.rectangle((cx + 2, cy + 2, cx + cell_w - 3, cy + cell_h - 3), fill=PREVIEW_CELL,
                    outline=PREVIEW_BORDER)
        g = glyph_image(grid).resize((CELL * scale, CELL * scale), Image.NEAREST)
        gx = cx + (cell_w - CELL * scale) // 2
        gy = cy + 8
        # 1 px checker-free frame that shows the 16x16 cell bounds.
        d.rectangle((gx - 1, gy - 1, gx + CELL * scale, gy + CELL * scale), outline=PREVIEW_BORDER)
        im.alpha_composite(g, (gx, gy))
        d.text((cx + 6, cy + 4), str(i), font=tiny, fill=PREVIEW_MUTED)
        label = name.lower()
        tw = d.textlength(label, font=small)
        d.text((cx + (cell_w - tw) / 2, gy + CELL * scale + 6), label, font=small, fill=PREVIEW_MUTED)
    return im


def render_review(out_dir: str, per_sheet: int = 8) -> None:
    """Per-glyph sheets: each glyph at 16 px (8x zoom) next to nearest-neighbour downscales to
    12, 10 and 8 px (also zoomed) - what Slate actually shows at the small sizes."""
    os.makedirs(out_dir, exist_ok=True)
    zoom = 8
    sizes = (16, 12, 10, 8)
    col_w = 16 * zoom + 20
    row_h = 16 * zoom + 28
    font = _font(12)
    for s in range(0, len(GLYPHS), per_sheet):
        chunk = GLYPHS[s:s + per_sheet]
        im = Image.new("RGBA", (20 + len(chunk) * col_w, 20 + len(sizes) * row_h), PREVIEW_BG)
        d = ImageDraw.Draw(im)
        for c, (name, grid) in enumerate(chunk):
            base = glyph_image(grid)
            x0 = 20 + c * col_w
            d.text((x0, 4), f"{s + c} {name.lower()}", font=font, fill=PREVIEW_TEXT)
            for r, size in enumerate(sizes):
                y0 = 20 + r * row_h + 14
                small = base if size == 16 else base.resize((size, size), Image.NEAREST)
                zoomed = small.resize((size * zoom, size * zoom), Image.NEAREST)
                d.rectangle((x0 - 1, y0 - 1, x0 + 16 * zoom, y0 + 16 * zoom), fill=PREVIEW_CELL,
                            outline=PREVIEW_BORDER)
                im.alpha_composite(zoomed, (x0, y0))
                d.text((x0, y0 - 13), f"{size}px", font=font, fill=PREVIEW_MUTED)
        im.save(os.path.join(out_dir, f"review_{s // per_sheet:02d}.png"))


def main(argv: list[str]) -> int:
    check_only = "--check" in argv
    review_dir = None
    if "--review" in argv:
        review_dir = argv[argv.index("--review") + 1]
    print(f"{len(GLYPHS)} glyphs -> {COLUMNS} x {atlas_rows()} cells")
    if check_only:
        return 0
    os.makedirs(os.path.dirname(ATLAS_PATH), exist_ok=True)
    render_atlas().save(ATLAS_PATH, optimize=True)
    print("wrote", os.path.relpath(ATLAS_PATH, ROOT))
    with open(JAVA_PATH, "w", encoding="utf-8", newline="\n") as f:
        f.write(java_source())
    print("wrote", os.path.relpath(JAVA_PATH, ROOT))
    render_preview().save(PREVIEW_PATH, optimize=True)
    print("wrote", os.path.relpath(PREVIEW_PATH, ROOT))
    if review_dir:
        render_review(review_dir)
        print("wrote review sheets to", review_dir)
    return 0


