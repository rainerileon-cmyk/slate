def main() -> int:
    for module, (modid, art) in ICONS.items():
        path = os.path.join(ROOT, "common", module, "src", "main", "resources", "assets", modid, "icon.png")
        os.makedirs(os.path.dirname(path), exist_ok=True)
        render(art).save(path, optimize=True)
        print("wrote", os.path.relpath(path, ROOT))
    return 0


